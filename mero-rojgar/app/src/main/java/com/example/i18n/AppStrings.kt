fun formatNpr(amountNpr: Long, locale: AppLocale): String {
    val formatted = NumberFormat.getNumberInstance(Locale("en", "IN")).format(amountNpr)
    return if (locale == AppLocale.NE) "रु $formatted" else "NPR $formatted"
}

fun formatPaisaAsNpr(paisa: Long, locale: AppLocale): String {
    val whole = paisa / 100
    val remainder = (paisa % 100).toInt()
    val prefix = if (locale == AppLocale.NE) "रु" else "NPR"
    return if (remainder == 0) "$prefix $whole" else "$prefix $whole.${remainder.toString().padStart(2, '0')}"
}
